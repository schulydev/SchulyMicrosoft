from abc import ABC, abstractmethod


class IGraphClient(ABC):
    """What the application asks of a per-account Graph client. OutNote is registered as one by the infrastructure."""

    @abstractmethod
    def get(self, path, params=None, client=None, raw=False): ...

    @abstractmethod
    def list(self, path, params=None, limit=None, client=None): ...

    @abstractmethod
    def post(self, path, body=None, client=None): ...

    @abstractmethod
    def emails(self, folder="inbox", top=25, unread=False, search=None, select=None): ...

    @abstractmethod
    def email(self, message_id): ...

    @abstractmethod
    def send_mail(self, to, subject, body, html=False, cc=None, bcc=None, attachments=None): ...

    @abstractmethod
    def create_draft(self, to, subject, body, html=False, cc=None, bcc=None, attachments=None): ...

    @abstractmethod
    def send_draft(self, message_id): ...

    @abstractmethod
    def reply(self, message_id, comment, reply_all=False): ...

    @abstractmethod
    def forward(self, message_id, to, comment=""): ...

    @abstractmethod
    def mark_read(self, message_id, read=True): ...

    @abstractmethod
    def flag(self, message_id, status="flagged"): ...

    @abstractmethod
    def move_email(self, message_id, folder): ...

    @abstractmethod
    def delete_email(self, message_id): ...

    @abstractmethod
    def download_attachment(self, message_id, attachment_id): ...

    @abstractmethod
    def mail_folders(self, include_children=False): ...

    @abstractmethod
    def events(self, start=None, end=None, top=25): ...

    @abstractmethod
    def files(self, path="root", top=100): ...

    @abstractmethod
    def notebooks(self): ...

    @abstractmethod
    def mark_chat_read(self, chat_id): ...
